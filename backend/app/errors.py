def _display(name: str, value: Any, region: str) -> Any:
    """Amounts in a message are rupiah figures ("Rp 1.234.567"); units are grouped numbers."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return value
    if name == "amount" or name.endswith("_amount"):
        return format_money(int(value), region, "figure")
    if name.endswith("_units"):
        text = f"{value:,}" if isinstance(value, int) else f"{value:,.4f}".rstrip("0").rstrip(".")
        return text if region == "US" else text.translate(str.maketrans(",.", ".,"))
    return value


def error_message(code: ErrorCode, params: dict[str, Any], *, language: str, region: str,
                  message_key: str | None = None) -> str:
    values = {name: _display(name, value, region) for name, value in params.items()}
    return t(language, f"error_messages.{message_key}" if message_key else f"errors.{code}", **values)


def error_detail(
    code: ErrorCode | str,
    params: dict[str, Any] | None = None,
    *,
    extra: dict[str, Any] | None = None,
    message_key: str | None = None,
    language: str | None = None,
    region: str | None = None,
) -> dict[str, Any]:
    code = ErrorCode(code)
    params = dict(params or {})
    message = error_message(
        code, params, language=language or current_language(), region=region or current_region(), message_key=message_key,
    )
    return {**(extra or {}), "code": code.value, "params": params, "message": message}


def api_error(
    status: int,
    code: ErrorCode | str,
    params: dict[str, Any] | None = None,
    *,
    extra: dict[str, Any] | None = None,
    message_key: str | None = None,
    language: str | None = None,
    headers: dict[str, str] | None = None,
) -> HTTPException:
    """An HTTPException with the contract's `detail`. A string code must be an `ErrorCode` value."""
    detail = error_detail(code, params, extra=extra, message_key=message_key, language=language)
    return HTTPException(status_code=status, detail=detail, headers=headers)
